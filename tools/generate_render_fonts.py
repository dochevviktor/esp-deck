"""Reproduce the bundled 4-bpp glyphs using the pinned ESPHome/FreeType rasterizer."""
import argparse
import hashlib
from importlib.metadata import version
import json
from pathlib import Path

import freetype
from esphome.components.font import glyph_to_glyphinfo, pt_to_px

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/DejaVuSans.ttf"
FONT_SHA256 = "7da195a74c55bef988d0d48f9508bd5d849425c1770dba5d7bfc6ce9ed848954"
LICENSE_SHA256 = "7a083b136e64d064794c3419751e5c7dd10d2f64c108fe5ba161eae5e5958a93"
SIZES = (12, 16, 20)
CODEPOINTS = (*range(0x20, 0x7f), *range(0xa0, 0x100))


def generate():
    if (version("esphome"), version("freetype-py"), freetype.version()) != ("2026.9.0", "2.5.1", (2, 13, 2)):
        raise RuntimeError("Font generation requires ESPHome 2026.9.0, freetype-py 2.5.1 / FreeType 2.13.2")
    if hashlib.sha256(FONT.read_bytes()).hexdigest() != FONT_SHA256:
        raise RuntimeError("Bundled font source differs from the DejaVu 2.37 pin")
    if hashlib.sha256((FONT.parent / "LICENSE-DejaVu.txt").read_bytes()).hexdigest() != LICENSE_SHA256:
        raise RuntimeError("Bundled font license differs from the upstream release")
    font = freetype.Face(str(FONT))
    lines = ["// Generated by tools/generate_render_fonts.py; do not edit.",
             "// DejaVu Sans 2.37; see assets/fonts/LICENSE-DejaVu.txt and THIRD_PARTY_NOTICES.md.",
             '#include "render_font.h"', "", "namespace esphome::stream_deck::rendering {", "namespace {"]
    manifest = {"family": "DejaVu Sans", "release": "2.37", "source_sha256": FONT_SHA256,
                "license_sha256": LICENSE_SHA256,
                "source_url": "https://github.com/dejavu-fonts/dejavu-fonts/releases/download/version_2_37/dejavu-fonts-ttf-2.37.tar.bz2",
                "archive_sha256": "fa9ca4d13871dd122f61258a80d01751d603b4d3ee14095d65453b4e846e17d7",
                "esphome": version("esphome"), "freetype_py": version("freetype-py"),
                "freetype": ".".join(map(str, freetype.version())), "bpp": 4,
                "coverage": ["U+0020..U+007E", "U+00A0..U+00FF"], "fonts": {}}
    for size in SIZES:
        glyphs, bitmap, records = [], bytearray(), []
        for point in CODEPOINTS:
            if not font.get_char_index(point):
                raise RuntimeError(f"Missing promised glyph U+{point:04X}")
            g = glyph_to_glyphinfo(chr(point), font, size, 4)
            if not (0 <= g.advance <= 32 and 0 <= g.width <= 32 and 0 <= g.height <= 32
                    and -32 <= g.offset_x <= 32 and 0 <= g.offset_y <= 32):
                raise RuntimeError(f"Glyph exceeds bounded renderer metrics: U+{point:04X}")
            record = [point, len(bitmap), g.advance, g.width, g.height, g.offset_x, g.offset_y]
            records.append(record)
            glyphs.append("  {" + ", ".join(map(str, record)) + "},")
            bitmap.extend(g.bitmap_data)
        line_height = max(pt_to_px(font.size.height), max(r[6] + r[4] for r in records))
        if line_height > 32:
            raise RuntimeError("Font line height exceeds the renderer's two-line budget")
        lines.append(f"const uint8_t BITS_{size}[] = {{")
        lines.extend("  " + ", ".join(f"0x{x:02x}" for x in bitmap[n:n + 24]) + ","
                     for n in range(0, len(bitmap), 24))
        lines.extend(["};", f"const Glyph GLYPHS_{size}[] = {{", *glyphs, "};",
                      f"const Font FONT_{size}{{GLYPHS_{size}, {len(records)}, BITS_{size}, sizeof(BITS_{size}), {size}, {line_height}}};"])
        manifest["fonts"][str(size)] = {"glyphs": len(records), "bitmap_bytes": len(bitmap),
                                        "bitmap_sha256": hashlib.sha256(bitmap).hexdigest(),
                                        "line_height": line_height}
    lines.extend(["}  // namespace", "const Font *bundled_font(unsigned size) {", "  switch (size) {"])
    lines.extend(f"    case {size}: return &FONT_{size};" for size in SIZES)
    lines.extend(["    default: return nullptr;", "  }", "}", "}  // namespace esphome::stream_deck::rendering", ""])
    source = "\n".join(lines).encode()
    manifest["generated_sha256"] = hashlib.sha256(source).hexdigest()
    return {ROOT / "components/stream_deck/render_font_data.cpp": source,
            ROOT / "assets/fonts/manifest.json": (json.dumps(manifest, indent=2) + "\n").encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, contents in generate().items():
        if args.check:
            if path.read_bytes() != contents:
                raise SystemExit(f"Font asset differs: {path}")
        else:
            path.write_bytes(contents)
    print("Font assets verified" if args.check else "Font assets generated")


if __name__ == "__main__":
    main()
